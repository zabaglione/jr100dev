; Floor population, full-period RNG, and wall-blocked visibility.
SELECT_FLOOR:
    LDX #FLOORS
    STX FP
    RTS
RANDOM:
    LDAA G_RNG + 1
    LDAB #$55
    JSR MULTIPLY
    STAB $AA + 1
    STAA $AA
    LDAA G_RNG
    LDAB #$55
    JSR MULTIPLY
    ADDB $AA
    STAB $AA
    LDAA G_RNG + 1
    LDAB #$62
    JSR MULTIPLY
    ADDB $AA
    STAB $AA
    LDAB $AA + 1
    LDAA $AA
    ADDB #(($3619) & 255)
    ADCA #(($3619) >> 8)
    STAB G_RNG + 1
    STAA G_RNG
    JSR WORD_Z
    RTS
GENERATE_WORLD:
    LDAA G_FLOOR
    STAA GEN_FLOOR
    JSR SELECT_FLOOR
    LDX FP
    STX P1
    LDAB #((FLOOR_DATA_END) & 255)
    LDAA #((FLOOR_DATA_END) >> 8)
    STAB TEMP_WORD + 1
    STAA TEMP_WORD
    CLRA
GEN_ZERO:
    LDX P1
    STAA 0,X
    INX
    STX P1
    LDAB TEMP_WORD + 1
    LDAA TEMP_WORD
    SUBB #((1) & 255)
    SBCA #((1) >> 8)
    STAB TEMP_WORD + 1
    STAA TEMP_WORD
    JSR WORD_Z
    BNE GEN_ZERO_MORE
    BRA BUILD_ROOMS
GEN_ZERO_MORE:
    CLRA
    BRA GEN_ZERO
BUILD_ROOMS:
    JSR TERRAIN_LAYOUT
    JSR RANDOM
    ANDA #7
    ADDA #12
    TST G_DIFFICULTY
    BNE ITEM_COUNT_READY
    ADDA #4
ITEM_COUNT_READY:
    STAA ITEM_COUNT
    CLR PLACE_INDEX
GEN_RANDOM_ITEM:
    JSR RANDOM
    ANDA #31
    STAA INDEX_OFFSET + 1
    LDX #ITEM_WEIGHTS
    ADX INDEX_OFFSET
    LDAA 0,X
    STAA PLACE_TYPE
    JSR PLACE_ITEM
    DEC ITEM_COUNT
    BNE GEN_RANDOM_ITEM
    LDAA G_FLOOR
    CMPA #3
    BCS GEN_NO_RING
    JSR RANDOM
    ANDA #15
    BNE GEN_NO_RING
    LDAA #21
    STAA PLACE_TYPE
    JSR PLACE_ITEM
GEN_NO_RING:
    LDAA G_DIFFICULTY
    ASLA
    ADDA G_FLOOR
    ADDA #4
    CMPA #MAX_ENEMIES
    BLS POPULATION_READY
    LDAA #MAX_ENEMIES
POPULATION_READY:
    STAA G_ENEMY_COUNT
    CLR E_INDEX
GEN_ENEMY:
    JSR FREE_POSITION
    LDAA NX
    SUBA G_X
    BPL ARRIVAL_DX
    NEGA
ARRIVAL_DX:
    STAA TEMP
    LDAA NY
    SUBA G_Y
    BPL ARRIVAL_DY
    NEGA
ARRIVAL_DY:
    ADDA TEMP
    CMPA #6
    BCS GEN_ENEMY
    JSR ENEMY_POINTER
    LDAA NX
    STAA 0,X
    LDAA NY
    STAA 1,X
    LDAA G_FLOOR
    ASLA
    ADDA #4
    CMPA #15
    BLS KIND_LIMIT_READY
    LDAA #15
KIND_LIMIT_READY:
    STAA KIND_LIMIT
ENEMY_ROLL_KIND:
    JSR RANDOM
    ANDA #15
    CMPA KIND_LIMIT
    BCC ENEMY_ROLL_KIND
    TAB
    LDX #ENEMY_DISTRIBUTION
    STAB INDEX_OFFSET + 1
    ADX INDEX_OFFSET
    LDAA 0,X
    STAA CANDIDATE
    JSR ENEMY_POINTER
    STAA 2,X
    LDAB CANDIDATE
    DECB
    LDX #ENEMY_HP
    STAB INDEX_OFFSET + 1
    ADX INDEX_OFFSET
    LDAA 0,X
    JSR ENEMY_POINTER
    STAA 3,X
    LDAA #255
    STAA 4,X
    STAA 5,X
    INC E_INDEX
    LDAA E_INDEX
    CMPA G_ENEMY_COUNT
    BNE GEN_ENEMY
    JSR GENERATE_EXTRAS
    RTS
FREE_POSITION:
    JSR POLL_KEY
    JSR RANDOM
    ANDA #63
    CMPA #MAP_WIDTH - 1
    BCC FREE_POSITION
    TSTA
    BEQ FREE_POSITION
    STAA NX
    JSR RANDOM
    ANDA #31
    TSTA
    BEQ FREE_POSITION
    CMPA #MAP_HEIGHT - 1
    BEQ FREE_POSITION
    STAA NY
    TAB
    LDAA NX
    JSR CELL
    ANDA #127
    CMPA #1
    BNE FREE_POSITION
    LDAA NX
    CMPA G_X
    BNE POSITION_NOT_ENTRY
    LDAA NY
    CMPA G_Y
    BEQ FREE_POSITION
POSITION_NOT_ENTRY:
    JSR FIND_ENEMY
    TSTA
    BNE FREE_POSITION
    JSR FIND_ITEM
    TSTA
    BNE FREE_POSITION
    RTS
PLACE_ITEM:
    JSR FREE_POSITION
    LDAB PLACE_INDEX
    LDAA #3
    JSR MULTIPLY
    ADDB FP + 1
    ADCA FP
    ADDB #((ITEM_START) & 255)
    ADCA #((ITEM_START) >> 8)
    STAB ITEM_PTR + 1
    STAA ITEM_PTR
    LDX ITEM_PTR
    LDAA NX
    STAA 0,X
    LDAA NY
    STAA 1,X
    LDAA PLACE_TYPE
    STAA 2,X
    INC PLACE_INDEX
    RTS
FIND_ENEMY:
    LDX #FLOORS + ENEMY_START
    STX E_PTR
    LDAB #MAX_ENEMIES
FIND_ENEMY_LOOP:
    LDX E_PTR
    TST 3,X
    BEQ FIND_ENEMY_NEXT
    LDAA 0,X
    CMPA NX
    BNE FIND_ENEMY_NEXT
    LDAA 1,X
    CMPA NY
    BNE FIND_ENEMY_NEXT
    LDAA 2,X
    RTS
FIND_ENEMY_NEXT:
    LDX E_PTR
    ADX #8
    STX E_PTR
    CPX #FLOORS + ITEM_START
    BNE FIND_ENEMY_LOOP
    CLRA
    RTS
FIND_ITEM:
    LDX #FLOORS + ITEM_START
    STX ITEM_PTR
FIND_ITEM_LOOP:
    LDX ITEM_PTR
    TST 2,X
    BEQ FIND_ITEM_NEXT
    LDAA 0,X
    CMPA NX
    BNE FIND_ITEM_NEXT
    LDAA 1,X
    CMPA NY
    BNE FIND_ITEM_NEXT
    LDAA 2,X
    RTS
FIND_ITEM_NEXT:
    LDX ITEM_PTR
    ADX #3
    STX ITEM_PTR
    CPX #FLOORS + FLOOR_DATA_END
    BNE FIND_ITEM_LOOP
    CLRA
    RTS
ENEMY_POINTER:
    PSHA
    LDAA E_INDEX
    ASLA
    ASLA
    ASLA
    STAA INDEX_OFFSET + 1
    LDX #FLOORS + ENEMY_START
    ADX INDEX_OFFSET
    STX E_PTR
    PULA
    RTS
UPDATE_VISIBILITY:
    CLR NEW_SIGHT
    LDX #VISIBLE
    CLRA
VIS_CLEAR:
    STAA 0,X
    INX
    CPX #VISIBLE + MASK_BYTES
    BNE VIS_CLEAR
    LDAA G_X
    SUBA #5
    BCC VIS_START_X
    CLRA
VIS_START_X:
    STAA LOS_START_X
    LDAA G_X
    ADDA #5
    CMPA #MAP_WIDTH - 1
    BLS VIS_END_X
    LDAA #MAP_WIDTH - 1
VIS_END_X:
    STAA LOS_END_X
    LDAA G_Y
    ADDA #5
    CMPA #MAP_HEIGHT - 1
    BLS VIS_END_Y
    LDAA #MAP_HEIGHT - 1
VIS_END_Y:
    STAA LOS_END_Y
    LDAA G_Y
    SUBA #5
    BCC VIS_START_Y
    CLRA
VIS_START_Y:
    STAA LOS_TY
VIS_Y:
    JSR POLL_KEY
    LDAA LOS_START_X
    STAA LOS_TX
VIS_X:
    LDAA LOS_TX
    SUBA G_X
    BPL VIS_DX
    NEGA
VIS_DX:
    STAA LOS_DX
    LDAA LOS_TY
    SUBA G_Y
    BPL VIS_DY
    NEGA
VIS_DY:
    ADDA LOS_DX
    CMPA #5
    BHI VIS_NEXT
    JSR LINE_VISIBLE
    TSTA
    BEQ VIS_NEXT
    LDAA LOS_TX
    LDAB LOS_TY
    JSR MARK_VISIBLE
    LDAA LOS_TX
    LDAB LOS_TY
    JSR CELL
    BITA #128
    BNE VIS_REMEMBER
    INC NEW_SIGHT
VIS_REMEMBER:
    JSR MARK_SEEN
VIS_NEXT:
    INC LOS_TX
    LDAA LOS_TX
    CMPA LOS_END_X
    BLS VIS_X
    INC LOS_TY
    LDAA LOS_TY
    CMPA LOS_END_Y
    BLS VIS_Y
    RTS
LINE_VISIBLE:
    LDAA G_X
    STAA LOS_X
    LDAA G_Y
    STAA LOS_Y
    LDAA #1
    STAA LOS_SX
    STAA LOS_SY
    LDAA LOS_TX
    SUBA G_X
    BPL LINE_DX
    NEGA
    NEG LOS_SX
LINE_DX:
    STAA LOS_DX
    LDAA LOS_TY
    SUBA G_Y
    BPL LINE_DY
    NEGA
    NEG LOS_SY
LINE_DY:
    STAA LOS_DY
    LDAA LOS_DX
    SUBA LOS_DY
    STAA LOS_ERROR
LINE_LOOP:
    LDAA LOS_X
    CMPA LOS_TX
    BNE LINE_BLOCK
    LDAA LOS_Y
    CMPA LOS_TY
    BEQ LINE_YES
LINE_BLOCK:
    LDAA LOS_X
    LDAB LOS_Y
    JSR CELL
    ANDA #127
    BEQ LINE_NO
    CMPA #5
    BEQ LINE_NO
    LDAA LOS_ERROR
    ASLA
    STAA LOS_TWICE
    LDAA LOS_DY
    NEGA
    CMPA LOS_TWICE
    BGE LINE_SKIP_X
    LDAA LOS_ERROR
    SUBA LOS_DY
    STAA LOS_ERROR
    LDAA LOS_X
    ADDA LOS_SX
    STAA LOS_X
LINE_SKIP_X:
    LDAA LOS_TWICE
    CMPA LOS_DX
    BGE LINE_LOOP
    LDAA LOS_ERROR
    ADDA LOS_DX
    STAA LOS_ERROR
    LDAA LOS_Y
    ADDA LOS_SY
    STAA LOS_Y
    BRA LINE_LOOP
LINE_YES:
    LDAA #1
    RTS
LINE_NO:
    CLRA
    RTS
