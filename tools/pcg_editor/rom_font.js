function columnsToRows(columns) {
  return Array.from({ length: GLYPH_ROWS }, (_, row) => {
    let value = 0;
    columns.forEach((column, index) => {
      if ((column >> row) & 1) {
        value |= 1 << (6 - index);
      }
    });
    return value;
  });
}

