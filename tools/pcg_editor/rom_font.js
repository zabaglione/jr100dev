function semigraphicGlyph(index) {
  const rows = Array(8).fill(0);
  const regions = [
    { mask: 0x01, x: 0, y: 0, width: 4, height: 3 },
    { mask: 0x02, x: 4, y: 0, width: 4, height: 3 },
    { mask: 0x04, x: 0, y: 3, width: 4, height: 3 },
    { mask: 0x08, x: 4, y: 3, width: 4, height: 3 },
    { mask: 0x10, x: 0, y: 6, width: 8, height: 2 },
  ];
  for (const region of regions) {
    if (!(index & region.mask)) {
      continue;
    }
    const bits = ((1 << region.width) - 1) << (8 - region.x - region.width);
    for (let row = region.y; row < region.y + region.height; row += 1) {
      rows[row] |= bits;
    }
  }
  return rows;
}

export function createFallbackRomGlyphs() {
  const glyphs = Array.from({ length: ROM_GLYPH_COUNT }, () => Array(GLYPH_ROWS).fill(0));
  ASCII_COLUMNS.forEach((columns, code) => {
    glyphs[code] = columnsToRows(columns);
  });
  for (let index = 0; index < 32; index += 1) {
    glyphs[0x40 + index] = symbolGlyph(index);
    glyphs[0x60 + index] = semigraphicGlyph(index);
  }
  return glyphs;
}

function readLe32(bytes, offset) {
  return bytes[offset] | (bytes[offset + 1] << 8) | (bytes[offset + 2] << 16) | (bytes[offset + 3] << 24);
}

export function extractCharacterRom(input) {
  const bytes = input instanceof Uint8Array ? input : new Uint8Array(input);
  let offset = 0;
  if (bytes.length >= 16 && String.fromCharCode(...bytes.slice(0, 4)) === "PROG") {
    const version = readLe32(bytes, 4) >>> 0;
    if (version === 1) {
      const nameLength = readLe32(bytes, 8) >>> 0;
      const blockOffset = 12 + nameLength;
      if (blockOffset + 12 > bytes.length) {
        throw new RangeError("PROG version 1 header is truncated");
      }
      const startAddress = readLe32(bytes, blockOffset) >>> 0;
      const dataLength = readLe32(bytes, blockOffset + 4) >>> 0;
      const dataOffset = blockOffset + 12;
      const fontOffset = 0xe000 - startAddress;
      if (fontOffset < 0 || fontOffset + ROM_BYTE_COUNT > dataLength || dataOffset + dataLength > bytes.length) {
        throw new RangeError("PROG file does not contain the $E000-$E3FF character ROM");
      }
      offset = dataOffset + fontOffset;
    } else if (version === 2) {
      let sectionOffset = 8;
      let foundOffset = -1;
      while (sectionOffset + 8 <= bytes.length) {
        const identifier = String.fromCharCode(...bytes.slice(sectionOffset, sectionOffset + 4));
        const sectionLength = readLe32(bytes, sectionOffset + 4) >>> 0;
        const payloadOffset = sectionOffset + 8;
        const sectionEnd = payloadOffset + sectionLength;
        if (sectionEnd > bytes.length) {
          throw new RangeError("PROG section is truncated");
        }
        if (identifier === "PBIN" && sectionLength >= 8) {
          const startAddress = readLe32(bytes, payloadOffset) >>> 0;
          const dataLength = readLe32(bytes, payloadOffset + 4) >>> 0;
          const dataOffset = payloadOffset + 8;
          const fontOffset = 0xe000 - startAddress;
          if (fontOffset >= 0 && fontOffset + ROM_BYTE_COUNT <= dataLength && dataOffset + dataLength <= sectionEnd) {
            foundOffset = dataOffset + fontOffset;
            break;
          }
        }
        sectionOffset = sectionEnd;
      }
      if (foundOffset < 0) {
        throw new RangeError("PROG file does not contain the $E000-$E3FF character ROM");
      }
      offset = foundOffset;
    } else {
      throw new RangeError(`Unsupported PROG version: ${version}`);
    }
  } else if (bytes.length < ROM_BYTE_COUNT) {
    throw new RangeError("Character ROM file must contain at least 1024 bytes");
  }
  return Array.from({ length: ROM_GLYPH_COUNT }, (_, code) =>
    Array.from(bytes.slice(offset + code * GLYPH_ROWS, offset + (code + 1) * GLYPH_ROWS)),
  );
}
